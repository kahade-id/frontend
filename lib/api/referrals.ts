/**
 * Kahade — domain `referral` (kode undangan, riwayat, reward).
 */

import { readList } from "@/lib/api/response"

import { http } from "@/lib/api/client"
import type { ApplyReferralDto } from "@/lib/api/types"

export type ReferralCode = {
  code: string
  createdAt?: string
  /** Salinan dibuat otomatis? */
  autoGenerated?: boolean
}

export type ReferralStats = {
  totalInvited: number
  completed: number
  pending: number
  totalReward: number
}

export type ReferralReward = {
  id: string
  code: string
  amount: number
  status: string
  createdAt: string
}

export type ReferralHistoryEntry = {
  id: string
  invitedUsername: string
  status: string
  reward?: number
  completedAt?: string | null
  createdAt: string
}

export function getMyReferralCode(signal?: AbortSignal) {
  return http.get<ReferralCode>("/v1/referral/my-code", { auth: "required", retry: 1, signal })
}

export function regenerateReferralCode() {
  return http.post<ReferralCode>("/v1/referral/regenerate", undefined, { auth: "required" })
}

export function getReferralStats(signal?: AbortSignal) {
  return http.get<ReferralStats>("/v1/referral/stats", { auth: "required", signal })
}

export function getReferralRewards(signal?: AbortSignal) {
  return http
    .get<ReferralReward[]>("/v1/referral/rewards", { auth: "required", signal })
    .then((raw) => readList<ReferralReward>(raw, ["rewards"]))
}

export function getReferralHistory(signal?: AbortSignal) {
  return http
    .get<ReferralHistoryEntry[]>("/v1/referral/history", { auth: "required", retry: 1, signal })
    .then((raw) => readList<ReferralHistoryEntry>(raw, ["history", "referrals"]))
}

export function applyReferralCode(dto: ApplyReferralDto) {
  return http.post<ReferralCode, ApplyReferralDto>("/v1/referral/apply", dto, { auth: "required" })
}

/**
 * Papan peringkat referral — GET /v1/referral/leaderboard?limit.
 * Respons tidak berschema di spec (Redis-cached); field dinormalisasi
 * defensif dari alias yang masuk akal (rank/username/invitedCount/totalReward).
 */
export type ReferralLeaderboardEntry = {
  rank: number
  username: string
  fullName?: string
  avatarUrl?: string | null
  invitedCount: number
  totalReward: number
}

function pickNumber(record: Record<string, unknown>, keys: readonly string[]): number {
  for (const key of keys) {
    const value = record[key]
    if (typeof value === "number" && Number.isFinite(value)) return value
    if (typeof value === "string" && value.trim()) {
      const parsed = Number(value.replace(/[^\d.-]/g, ""))
      if (Number.isFinite(parsed)) return parsed
    }
  }
  return 0
}

export function getReferralLeaderboard(limit = 50, signal?: AbortSignal) {
  return http
    .get<unknown>("/v1/referral/leaderboard", {
      query: { limit },
      auth: "required",
      retry: 1,
      signal,
    })
    .then((raw) => {
      const rows = readList<unknown>(raw, ["leaderboard", "data"])
      return rows
        .map((row, index) => {
          const record = (row ?? {}) as Record<string, unknown>
          const username =
            typeof record.username === "string" && record.username
              ? record.username
              : typeof record.fullName === "string" && record.fullName
                ? record.fullName
                : ""
          if (!username) return null
          const entry: ReferralLeaderboardEntry = {
            rank: pickNumber(record, ["rank", "position"]) || index + 1,
            username,
            fullName:
              typeof record.fullName === "string" && record.fullName
                ? record.fullName
                : undefined,
            avatarUrl:
              typeof record.avatarUrl === "string"
                ? record.avatarUrl
                : (typeof record.avatar === "string" ? record.avatar : null),
            invitedCount: pickNumber(record, [
              "invitedCount",
              "totalInvited",
              "invited",
              "referralCount",
              "count",
            ]),
            totalReward: pickNumber(record, [
              "totalReward",
              "totalRewardAmount",
              "reward",
              "amount",
              "totalAmount",
            ]),
          }
          return entry
        })
        .filter((entry): entry is ReferralLeaderboardEntry => entry !== null)
    })
}
